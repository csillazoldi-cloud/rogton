-- Kézzel írt migráció, E-39: AI-költség és keret SZERVEZETENKÉNT.
-- Eddig egyetlen közös havi keret volt az egész rendszerre (ai_koltseg_honap). Az marad
-- rendszerszintű biztonsági fékként, de a valódi korlát mostantól szervezetenként van.

-- 1. A szervezet havi kerete. NULL = az AI_HAVI_KERET_USD alapérték érvényes rá.
ALTER TABLE "szervezet" ADD COLUMN IF NOT EXISTS "ai_keret_usd" numeric(10,2);

-- 2. Rendszergazda-nézet: minden szervezet havi összesítése.
--    SECURITY DEFINER, mert a sorszintű védelem miatt a km_app szerep csak a SAJÁT szervezetét látja.
--    CSAK ÖSSZESÍTÉST ad vissza (darabszám, idő, költség) — egyetlen cikk, prompt vagy válasz sem megy át rajta.
--    A hívó oldalon a rendszergazda-jogot az API ellenőrzi.
CREATE OR REPLACE FUNCTION ai_koltseg_osszes(p_honap text)
RETURNS TABLE (
  szervezet_id uuid, nev text, hivasok bigint, ido_ms bigint,
  usd numeric, utolso timestamptz, keret_usd numeric, szolgaltatok jsonb
)
LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  SELECT sz.id, sz.nev,
         count(h.id)::bigint,
         coalesce(sum(h.ido_ms), 0)::bigint,
         coalesce(sum(h.becsult_usd), 0)::numeric,
         max(h.letrehozva),
         sz.ai_keret_usd,
         coalesce((
           SELECT jsonb_object_agg(x.szolgaltato, x.db)
           FROM (SELECT h2.szolgaltato, count(*) AS db FROM ai_hivas h2
                 WHERE h2.szervezet_id = sz.id AND to_char(h2.letrehozva, 'YYYY-MM') = p_honap
                 GROUP BY h2.szolgaltato) x
         ), '{}'::jsonb)
  FROM szervezet sz
  LEFT JOIN ai_hivas h ON h.szervezet_id = sz.id AND to_char(h.letrehozva, 'YYYY-MM') = p_honap
  GROUP BY sz.id, sz.nev, sz.ai_keret_usd
  ORDER BY sz.nev;
$$;
REVOKE ALL ON FUNCTION ai_koltseg_osszes(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ai_koltseg_osszes(text) TO km_app;

-- 3. A keret beállítása (rendszergazda). Ugyanaz az ok: a km_app más szervezet sorát nem írhatja.
CREATE OR REPLACE FUNCTION ai_keret_allit(p_szervezet uuid, p_usd numeric)
RETURNS void
LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  UPDATE szervezet SET ai_keret_usd = p_usd WHERE id = p_szervezet;
$$;
REVOKE ALL ON FUNCTION ai_keret_allit(uuid, numeric) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ai_keret_allit(uuid, numeric) TO km_app;

