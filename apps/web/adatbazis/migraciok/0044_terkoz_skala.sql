-- A tárolt KÖZÖS ALAP kiegészítése a tizenöt térköz-fokkal (a TÁROLT érték nyer — E-44 tanulsága), és a hét
-- régi térköz-token (--gap, --pad-card, --pad-block, --pad-field-y, --pad-field-x, --btn-pad-y, --btn-pad-x)
-- kivétele a tárolt készletből: ezek mostantól a skálából származnak (szarmaztat()), nem tárolt alaptokenek.
UPDATE "tema"
SET "definicio" = jsonb_set(
  "definicio",
  '{tokens}',
  ('{"--ter-0":"0px","--ter-1":"2px","--ter-2":"4px","--ter-3":"6px","--ter-4":"8px","--ter-5":"10px","--ter-6":"12px","--ter-7":"14px","--ter-8":"16px","--ter-9":"20px","--ter-10":"24px","--ter-11":"32px","--ter-12":"40px","--ter-13":"56px","--ter-14":"80px"}'::jsonb
    || ("definicio" -> 'tokens'))
    - '--gap' - '--pad-card' - '--pad-block' - '--pad-field-y' - '--pad-field-x' - '--btn-pad-y' - '--btn-pad-x'
)
WHERE NOT ("definicio" -> 'tokens' ? '--ter-4') OR ("definicio" -> 'tokens' ? '--pad-card');

-- A szervezeti felülírásokból is kikerül a hét régi kulcs (egy szervezet a saját --pad-card értékét nem viheti át
-- egy az egyben a skálára; a teszten csak próbaszervezetek vannak — D-F08).
UPDATE "szervezet_tema"
SET "felulirasok" = "felulirasok" - '--gap' - '--pad-card' - '--pad-block' - '--pad-field-y' - '--pad-field-x' - '--btn-pad-y' - '--btn-pad-x'
WHERE "felulirasok" ?| array['--gap','--pad-card','--pad-block','--pad-field-y','--pad-field-x','--btn-pad-y','--btn-pad-x'];
