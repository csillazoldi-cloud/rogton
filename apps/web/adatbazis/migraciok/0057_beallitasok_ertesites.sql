);
GRANT SELECT, INSERT ON "ertesites_olvasott" TO "km_app";

-- 2. Hat új token (R-4 tokenek.md): --keszul (a „még nem működik" jelölés színe — nem hibaszín), --olvasatlan (az olvasatlan pont és a harang száma),
