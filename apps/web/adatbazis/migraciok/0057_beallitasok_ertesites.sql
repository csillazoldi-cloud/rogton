SET "definicio" = jsonb_set("definicio", '{tokens}',
  ('{"--keszul":"#9fb0d8","--olvasatlan":"#7f8fff","--kapcsolo-w":"38px","--kapcsolo-h":"22px"}'::jsonb || ("definicio" -> 'tokens')))
WHERE NOT ("definicio" -> 'tokens' ? '--keszul') OR NOT ("definicio" -> 'tokens' ? '--olvasatlan') OR NOT ("definicio" -> 'tokens' ? '--kapcsolo-w') OR NOT ("definicio" -> 'tokens' ? '--kapcsolo-h');

