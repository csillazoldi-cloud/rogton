  "frissitve" timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE ON "ertesites_fiok" TO "km_app";

CREATE TABLE IF NOT EXISTS "ertesites_olvasott" (
  "fiok_id" uuid NOT NULL REFERENCES "fiok"("id") ON DELETE CASCADE,
  "esemeny_id" uuid NOT NULL REFERENCES "esemeny"("id") ON DELETE CASCADE,
  "ido" timestamptz NOT NULL DEFAULT now(),
